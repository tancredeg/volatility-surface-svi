"""Build the bundled synthetic SPY-like sample from the calibrated real snapshot.

The raw vendor chain cannot be redistributed. This script publishes instead a
synthetic chain with the same expiries, forwards, discount factors, strike
coverage, quote noise and bid-ask widths as the real one:

    mid vol  = constrained-SVI vol of the real slice + N(0, s_T^2),
               s_T = residual std of that fit (per expiry);
    bid/ask  = Black-76 prices at mid vol -/+ the median real half-spread (vol),
               rounded outwards to the cent; calls and puts on every strike.

Only fitted parameters and summary statistics of the real data are used.

Usage (needs the raw chain referenced by data/snapshots/spy_20260603.json):
    python scripts/make_sample.py
"""

from __future__ import annotations

import json
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

from volsurf.data import load_snapshot, sha256_of
from volsurf.iv import black76_price
from volsurf.svi import calibrate_svi_surface

ROOT = Path(__file__).resolve().parents[1]
REAL = ROOT / "data/snapshots/spy_20260603.json"
OUT_CSV = ROOT / "data/sample/spy_like_20260603.csv"
OUT_META = ROOT / "data/sample/spy_like_20260603.json"
SEED = 20260603


def strike_grid(F: float, k_min: float, k_max: float) -> np.ndarray:
    """$1 strikes within 10% of the forward, $5 beyond, covering [k_min, k_max]."""
    lo, hi = F * np.exp(k_min), F * np.exp(k_max)
    fine = np.arange(np.ceil(0.9 * F), np.floor(1.1 * F) + 1, 1.0)
    coarse = np.arange(5 * np.ceil(lo / 5), 5 * np.floor(hi / 5) + 5, 5.0)
    k = np.unique(np.concatenate([fine, coarse]))
    return k[(k >= lo) & (k <= hi)]


def main() -> None:
    warnings.filterwarnings("ignore", message="Values in x were outside bounds")
    snap = load_snapshot(REAL)
    fits = calibrate_svi_surface([(s.maturity, s.k, s.iv_mid) for s in snap.slices], constrained=True)
    rng = np.random.default_rng(SEED)
    rows = []
    stats = []
    for s, fit in zip(snap.slices, fits, strict=True):
        resid = fit.params.implied_vol(s.k, s.maturity) - s.iv_mid
        noise = float(np.std(resid))
        half = float(np.median(s.iv_ask - s.iv_bid) / 2)
        K = strike_grid(s.forward, s.k_range[0] - 0.02, s.k_range[1] + 0.02)
        k = np.log(K / s.forward)
        vol = fit.params.implied_vol(k, s.maturity) + rng.normal(0.0, noise, size=k.shape)
        for is_call, name in ((True, "call"), (False, "put")):
            bid = black76_price(s.forward, K, s.maturity, s.discount, vol - half, is_call)
            ask = black76_price(s.forward, K, s.maturity, s.discount, vol + half, is_call)
            bid = np.floor(bid * 100) / 100
            ask = np.maximum(np.ceil(ask * 100) / 100, bid + 0.01)
            rows.append(
                pd.DataFrame({"expiry": s.expiry, "option_type": name, "strike": K, "bid": bid, "ask": ask})
            )
        # rounded: the fits are reproducible to ~1e-11, the metadata must be byte-stable
        stats.append(
            {
                "expiry": s.expiry,
                "noise_vol": round(noise, 8),
                "half_spread_vol": round(half, 8),
                "strikes": len(K),
            }
        )
    chain = pd.concat(rows, ignore_index=True)
    chain = chain[chain["bid"] > 0].sort_values(["expiry", "option_type", "strike"])
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    chain.to_csv(OUT_CSV, index=False, float_format="%.2f")
    real = json.loads(REAL.read_text(encoding="utf-8"))
    meta = {
        "underlying": "SPY-like (synthetic)",
        "description": "Synthetic option chain generated by scripts/make_sample.py from constrained-SVI fits of the "
        "real SPY snapshot of 2026-06-03 (same expiries, forwards, discounting, strike coverage, "
        "quote noise and bid-ask widths). Not market data.",
        "chain_file": str(OUT_CSV.relative_to(ROOT)),
        "chain_sha256": sha256_of(OUT_CSV),
        "valuation_time_utc": real["valuation_time_utc"],
        "rate": real["rate"],
        "dividends": real["dividends"],
        "synthetic": True,
        "generator": {"seed": SEED, "per_expiry": stats},
    }
    OUT_META.write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_CSV.relative_to(ROOT)} ({len(chain)} quotes) and {OUT_META.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
